-- =============================================================
-- 16_account_phone_aliases.sql — account-service (schema BANK_ACCOUNT)
-- Alias số điện thoại → tài khoản nhận cho chuyển tiền qua số điện thoại.
-- Một số điện thoại chỉ trỏ tới một tài khoản và mỗi tài khoản có tối đa một alias.
-- PHONE_HASH là blind index HMAC-SHA256 của số điện thoại đã chuẩn hóa (cùng khóa với CUSTOMERS.PHONE_HASH);
-- không lưu số điện thoại dạng rõ.
-- Chạy bằng user bank_account (bảng có IDENTITY), đặt NLS_LANG=AMERICAN_AMERICA.AL32UTF8.
-- =============================================================

CREATE TABLE PHONE_ALIASES (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PHONE_HASH   VARCHAR2(64 CHAR)  NOT NULL,
    ACCOUNT_ID   NUMBER(19)         NOT NULL,
    CUSTOMER_ID  NUMBER(19)         NOT NULL,   -- tham chiếu BANK_CUSTOMER.CUSTOMERS.ID (không FK liên schema)
    CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PHONE_ALIASES PRIMARY KEY (ID),
    CONSTRAINT UK_PHONE_ALIASES_PHONE UNIQUE (PHONE_HASH),
    CONSTRAINT UK_PHONE_ALIASES_ACCOUNT UNIQUE (ACCOUNT_ID),
    CONSTRAINT FK_PHONE_ALIASES_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS (ID)
);
CREATE INDEX IX_PHONE_ALIASES_CUSTOMER ON PHONE_ALIASES (CUSTOMER_ID);

COMMENT ON TABLE PHONE_ALIASES IS 'Alias số điện thoại → tài khoản nhận (chuyển tiền qua số điện thoại)';
COMMENT ON COLUMN PHONE_ALIASES.PHONE_HASH IS 'Blind index HMAC-SHA256 của số điện thoại đã chuẩn hóa';
