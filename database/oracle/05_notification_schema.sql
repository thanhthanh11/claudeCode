-- 05_notification_schema.sql — notification-service (schema BANK_NOTIFICATION)
-- Mẫu thông báo và lịch sử gửi thông báo.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_NOTIFICATION;

CREATE TABLE NOTIFICATION_TEMPLATES (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODE        VARCHAR2(50 CHAR)    NOT NULL,
    CHANNEL     VARCHAR2(10 CHAR)    NOT NULL,
    SUBJECT     VARCHAR2(255 CHAR),
    BODY        VARCHAR2(4000 CHAR)  NOT NULL,
    ACTIVE      NUMBER(1)            DEFAULT 1 NOT NULL,
    CREATED_AT  TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICATION_TEMPLATES PRIMARY KEY (ID),
    CONSTRAINT UK_NOTIF_TEMPLATES_CODE UNIQUE (CODE, CHANNEL),
    CONSTRAINT CK_NOTIF_TEMPLATES_CHANNEL CHECK (CHANNEL IN ('EMAIL', 'SMS')),
    CONSTRAINT CK_NOTIF_TEMPLATES_ACTIVE CHECK (ACTIVE IN (0, 1))
);
COMMENT ON TABLE NOTIFICATION_TEMPLATES IS 'Mẫu nội dung thông báo';

CREATE TABLE NOTIFICATIONS (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    EVENT_ID       VARCHAR2(64 CHAR)    NOT NULL,       -- ID sự kiện Kafka, dùng chống gửi trùng
    CUSTOMER_ID    NUMBER(19),                          -- BANK_CUSTOMER.CUSTOMERS.ID
    TEMPLATE_CODE  VARCHAR2(50 CHAR),
    CHANNEL        VARCHAR2(10 CHAR)    NOT NULL,
    RECIPIENT      VARCHAR2(150 CHAR)   NOT NULL,
    SUBJECT        VARCHAR2(255 CHAR),
    CONTENT        VARCHAR2(4000 CHAR)  NOT NULL,
    STATUS         VARCHAR2(20 CHAR)    DEFAULT 'PENDING' NOT NULL,
    RETRY_COUNT    NUMBER(3)            DEFAULT 0 NOT NULL,
    ERROR_MESSAGE  VARCHAR2(1000 CHAR),
    SENT_AT        TIMESTAMP,
    CREATED_AT     TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY (ID),
    CONSTRAINT UK_NOTIFICATIONS_EVENT UNIQUE (EVENT_ID, CHANNEL),
    CONSTRAINT CK_NOTIFICATIONS_CHANNEL CHECK (CHANNEL IN ('EMAIL', 'SMS')),
    CONSTRAINT CK_NOTIFICATIONS_STATUS CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED'))
);
CREATE INDEX IX_NOTIFICATIONS_CUSTOMER ON NOTIFICATIONS (CUSTOMER_ID, CREATED_AT);
CREATE INDEX IX_NOTIFICATIONS_STATUS ON NOTIFICATIONS (STATUS);
COMMENT ON TABLE NOTIFICATIONS IS 'Lịch sử thông báo đã/đang gửi';

