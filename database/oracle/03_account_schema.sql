-- =============================================================
-- 03_account_schema.sql — account-service (schema BANK_ACCOUNT)
-- Tài khoản, số dư và sổ cái biến động số dư.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_ACCOUNT;

CREATE TABLE ACCOUNTS (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ACCOUNT_NUMBER     VARCHAR2(20 CHAR)  NOT NULL,
    CUSTOMER_ID        NUMBER(19)         NOT NULL,     -- tham chiếu BANK_CUSTOMER.CUSTOMERS.ID (không FK liên schema)
    ACCOUNT_TYPE       VARCHAR2(20 CHAR)  NOT NULL,
    CURRENCY           CHAR(3 CHAR)       DEFAULT 'VND' NOT NULL,
    BALANCE            NUMBER(19,4)       DEFAULT 0 NOT NULL,
    AVAILABLE_BALANCE  NUMBER(19,4)       DEFAULT 0 NOT NULL,
    STATUS             VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    OPENED_AT          TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CLOSED_AT          TIMESTAMP,
    VERSION            NUMBER(19)         DEFAULT 0 NOT NULL,   -- optimistic locking (@Version)
    CREATED_AT         TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ACCOUNTS PRIMARY KEY (ID),
    CONSTRAINT UK_ACCOUNTS_NUMBER UNIQUE (ACCOUNT_NUMBER),
    CONSTRAINT CK_ACCOUNTS_TYPE CHECK (ACCOUNT_TYPE IN ('PAYMENT', 'SAVINGS')),
    CONSTRAINT CK_ACCOUNTS_STATUS CHECK (STATUS IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT CK_ACCOUNTS_BALANCE CHECK (BALANCE >= 0 AND AVAILABLE_BALANCE >= 0 AND AVAILABLE_BALANCE <= BALANCE)
);
CREATE INDEX IX_ACCOUNTS_CUSTOMER ON ACCOUNTS (CUSTOMER_ID);
COMMENT ON TABLE ACCOUNTS IS 'Tài khoản ngân hàng và số dư';

CREATE TABLE ACCOUNT_LEDGER_ENTRIES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ACCOUNT_ID       NUMBER(19)         NOT NULL,
    TRANSACTION_REF  VARCHAR2(40 CHAR)  NOT NULL,       -- tham chiếu BANK_TRANSACTION.TRANSACTIONS.TRANSACTION_REF
    ENTRY_TYPE       VARCHAR2(10 CHAR)  NOT NULL,
    AMOUNT           NUMBER(19,4)       NOT NULL,
    BALANCE_AFTER    NUMBER(19,4)       NOT NULL,
    DESCRIPTION      VARCHAR2(255 CHAR),
    CREATED_AT       TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ACCOUNT_LEDGER_ENTRIES PRIMARY KEY (ID),
    CONSTRAINT FK_LEDGER_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS (ID),
    -- Một giao dịch chỉ ghi một bút toán mỗi loại cho một tài khoản (chống xử lý trùng)
    CONSTRAINT UK_LEDGER_TXN_ENTRY UNIQUE (ACCOUNT_ID, TRANSACTION_REF, ENTRY_TYPE),
    CONSTRAINT CK_LEDGER_ENTRY_TYPE CHECK (ENTRY_TYPE IN ('DEBIT', 'CREDIT')),
    CONSTRAINT CK_LEDGER_AMOUNT CHECK (AMOUNT > 0)
);
CREATE INDEX IX_LEDGER_ACCOUNT_CREATED ON ACCOUNT_LEDGER_ENTRIES (ACCOUNT_ID, CREATED_AT);
CREATE INDEX IX_LEDGER_TXN_REF ON ACCOUNT_LEDGER_ENTRIES (TRANSACTION_REF);
COMMENT ON TABLE ACCOUNT_LEDGER_ENTRIES IS 'Sổ cái biến động số dư (chỉ thêm mới, không sửa/xóa)';
