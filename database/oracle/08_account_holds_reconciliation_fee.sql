-- Tạm giữ (phong tỏa một phần số dư): AVAILABLE_BALANCE = BALANCE - tổng các hold ACTIVE
CREATE TABLE ACCOUNT_HOLDS (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ACCOUNT_ID   NUMBER(19)          NOT NULL,
    AMOUNT       NUMBER(19,4)        NOT NULL,
    REASON       VARCHAR2(255 CHAR)  NOT NULL,
    STATUS       VARCHAR2(20 CHAR)   DEFAULT 'ACTIVE' NOT NULL,
    EXPIRES_AT   TIMESTAMP,                              -- null = giữ tới khi giải tỏa thủ công
    CREATED_BY   VARCHAR2(100 CHAR)  NOT NULL,
    RELEASED_BY  VARCHAR2(100 CHAR),
    RELEASED_AT  TIMESTAMP,
    CREATED_AT   TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ACCOUNT_HOLDS PRIMARY KEY (ID),
    CONSTRAINT FK_HOLDS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS (ID),
    CONSTRAINT CK_HOLDS_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_HOLDS_STATUS CHECK (STATUS IN ('ACTIVE', 'RELEASED'))
);
CREATE INDEX IX_HOLDS_ACCOUNT_STATUS ON ACCOUNT_HOLDS (ACCOUNT_ID, STATUS);
CREATE INDEX IX_HOLDS_STATUS_EXPIRES ON ACCOUNT_HOLDS (STATUS, EXPIRES_AT);
COMMENT ON TABLE ACCOUNT_HOLDS IS 'Tạm giữ tiền trên tài khoản (giảm số dư khả dụng)';

-- Kết quả đối soát số dư với sổ cái
CREATE TABLE RECONCILIATION_ISSUES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ACCOUNT_ID       NUMBER(19)          NOT NULL,
    ACCOUNT_NUMBER   VARCHAR2(20 CHAR)   NOT NULL,
    ISSUE_TYPE       VARCHAR2(30 CHAR)   NOT NULL,
    EXPECTED_AMOUNT  NUMBER(19,4)        NOT NULL,       -- giá trị tính từ sổ cái / hold
    ACTUAL_AMOUNT    NUMBER(19,4)        NOT NULL,       -- giá trị đang lưu trên ACCOUNTS
    DETECTED_AT      TIMESTAMP           NOT NULL,
    RESOLVED         NUMBER(1)           DEFAULT 0 NOT NULL,
    RESOLVED_AT      TIMESTAMP,
    NOTE             VARCHAR2(500 CHAR),
    CREATED_AT       TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RECONCILIATION_ISSUES PRIMARY KEY (ID),
    CONSTRAINT CK_RECON_ISSUE_TYPE CHECK (ISSUE_TYPE IN ('BALANCE_MISMATCH', 'AVAILABLE_BALANCE_MISMATCH')),
    CONSTRAINT CK_RECON_RESOLVED CHECK (RESOLVED IN (0, 1))
);
CREATE INDEX IX_RECON_RESOLVED ON RECONCILIATION_ISSUES (RESOLVED, DETECTED_AT);
COMMENT ON TABLE RECONCILIATION_ISSUES IS 'Sai lệch giữa số dư tài khoản và sổ cái phát hiện khi đối soát';

COMMIT;
