-- =============================================================
-- 19_interbank_schema.sql — interbank-service (schema BANK_INTERBANK)
-- Danh mục ngân hàng Napas, lệnh chuyển đi (OUTBOUND_TRANSFERS) và tiền đến (INBOUND_TRANSFERS).
-- Hai bảng lệnh kiêm vai trò outbox: cờ RESULT_PUBLISHED / EVENT_PUBLISHED = 0 nghĩa là kết quả chưa được
-- publish lên Kafka (ghi cùng transaction với thay đổi trạng thái, job publish at-least-once).
-- Tên chủ tài khoản đối tác mã hóa AES-GCM ở tầng ứng dụng (enc:v1:...).
-- Chạy bằng user bank_interbank (bảng có IDENTITY), đặt NLS_LANG=AMERICAN_AMERICA.AL32UTF8.
-- =============================================================

CREATE TABLE INTERBANK_BANKS (
    BANK_CODE   VARCHAR2(20 CHAR)   NOT NULL,     -- BIN Napas
    SHORT_NAME  VARCHAR2(50 CHAR)   NOT NULL,
    FULL_NAME   VARCHAR2(255 CHAR)  NOT NULL,
    ACTIVE      NUMBER(1)           DEFAULT 1 NOT NULL,
    CREATED_AT  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INTERBANK_BANKS PRIMARY KEY (BANK_CODE),
    CONSTRAINT CK_INTERBANK_BANKS_ACTIVE CHECK (ACTIVE IN (0, 1))
);
COMMENT ON TABLE INTERBANK_BANKS IS 'Danh mục ngân hàng thành viên Napas 247';

CREATE TABLE OUTBOUND_TRANSFERS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    TRANSACTION_REF      VARCHAR2(40 CHAR)   NOT NULL,   -- BANK_TRANSACTION.TRANSACTIONS.TRANSACTION_REF
    FROM_ACCOUNT_NUMBER  VARCHAR2(20 CHAR)   NOT NULL,
    BANK_CODE            VARCHAR2(20 CHAR)   NOT NULL,
    BENEFICIARY_ACCOUNT  VARCHAR2(34 CHAR)   NOT NULL,
    BENEFICIARY_NAME     VARCHAR2(400 CHAR),
    AMOUNT               NUMBER(19,4)        NOT NULL,
    CURRENCY             CHAR(3 CHAR)        NOT NULL,
    DESCRIPTION          VARCHAR2(255 CHAR),
    STATUS               VARCHAR2(20 CHAR)   DEFAULT 'NEW' NOT NULL,
    NAPAS_REF            VARCHAR2(64 CHAR),
    REASON               VARCHAR2(500 CHAR),
    ATTEMPTS             NUMBER(5)           DEFAULT 0 NOT NULL,
    NEXT_ATTEMPT_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    RESULT_PUBLISHED     NUMBER(1)           DEFAULT 0 NOT NULL,
    COMPLETED_AT         TIMESTAMP,
    CREATED_AT           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OUTBOUND_TRANSFERS PRIMARY KEY (ID),
    CONSTRAINT UK_OUTBOUND_TRANSFERS_REF UNIQUE (TRANSACTION_REF),
    CONSTRAINT CK_OUTBOUND_STATUS CHECK (STATUS IN ('NEW', 'UNKNOWN', 'COMPLETED', 'REJECTED')),
    CONSTRAINT CK_OUTBOUND_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_OUTBOUND_PUBLISHED CHECK (RESULT_PUBLISHED IN (0, 1))
);
CREATE INDEX IX_OUTBOUND_STATUS ON OUTBOUND_TRANSFERS (STATUS, NEXT_ATTEMPT_AT);
CREATE INDEX IX_OUTBOUND_PUBLISH ON OUTBOUND_TRANSFERS (RESULT_PUBLISHED, STATUS);
COMMENT ON TABLE OUTBOUND_TRANSFERS IS 'Lệnh chuyển tiền ra ngân hàng khác gửi Napas (idempotent theo TRANSACTION_REF)';
COMMENT ON COLUMN OUTBOUND_TRANSFERS.STATUS IS 'NEW chưa gửi; UNKNOWN đã gửi chưa rõ kết quả (tra soát); COMPLETED / REJECTED kết quả cuối';
COMMENT ON COLUMN OUTBOUND_TRANSFERS.BENEFICIARY_NAME IS 'Tên người nhận, mã hóa AES-GCM (enc:v1:...)';

CREATE TABLE INBOUND_TRANSFERS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NAPAS_REF            VARCHAR2(40 CHAR)   NOT NULL,
    SOURCE_BANK_CODE     VARCHAR2(20 CHAR)   NOT NULL,
    SOURCE_ACCOUNT       VARCHAR2(34 CHAR)   NOT NULL,
    SOURCE_NAME          VARCHAR2(400 CHAR),
    BENEFICIARY_ACCOUNT  VARCHAR2(20 CHAR)   NOT NULL,
    AMOUNT               NUMBER(19,4)        NOT NULL,
    CURRENCY             CHAR(3 CHAR)        NOT NULL,
    DESCRIPTION          VARCHAR2(255 CHAR),
    STATUS               VARCHAR2(20 CHAR)   DEFAULT 'RECEIVED' NOT NULL,
    TRANSACTION_REF      VARCHAR2(40 CHAR),                -- giao dịch INTERBANK_IN ở transaction-service
    REASON               VARCHAR2(500 CHAR),
    EVENT_PUBLISHED      NUMBER(1)           DEFAULT 0 NOT NULL,
    CALLBACK_STATUS      VARCHAR2(20 CHAR),
    CALLBACK_ATTEMPTS    NUMBER(5)           DEFAULT 0 NOT NULL,
    NEXT_CALLBACK_AT     TIMESTAMP,
    CREATED_AT           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INBOUND_TRANSFERS PRIMARY KEY (ID),
    CONSTRAINT UK_INBOUND_TRANSFERS_NAPAS_REF UNIQUE (NAPAS_REF),
    CONSTRAINT CK_INBOUND_STATUS CHECK (STATUS IN ('RECEIVED', 'SETTLED', 'RETURNED')),
    CONSTRAINT CK_INBOUND_CALLBACK CHECK (CALLBACK_STATUS IS NULL OR CALLBACK_STATUS IN ('PENDING', 'DONE', 'FAILED')),
    CONSTRAINT CK_INBOUND_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_INBOUND_PUBLISHED CHECK (EVENT_PUBLISHED IN (0, 1))
);
CREATE INDEX IX_INBOUND_PUBLISH ON INBOUND_TRANSFERS (EVENT_PUBLISHED, STATUS);
CREATE INDEX IX_INBOUND_CALLBACK ON INBOUND_TRANSFERS (CALLBACK_STATUS, NEXT_CALLBACK_AT);
COMMENT ON TABLE INBOUND_TRANSFERS IS 'Tiền từ ngân hàng khác chuyển đến qua Napas (idempotent theo NAPAS_REF)';
COMMENT ON COLUMN INBOUND_TRANSFERS.SOURCE_NAME IS 'Tên người gửi, mã hóa AES-GCM (enc:v1:...)';

