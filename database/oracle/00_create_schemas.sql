CREATE USER BANK_AUTH IDENTIFIED BY "ChangeMe_Auth1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER BANK_CUSTOMER IDENTIFIED BY "ChangeMe_Customer1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER BANK_ACCOUNT IDENTIFIED BY "ChangeMe_Account1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER BANK_TRANSACTION IDENTIFIED BY "ChangeMe_Transaction1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER BANK_NOTIFICATION IDENTIFIED BY "ChangeMe_Notification1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO BANK_AUTH;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO BANK_CUSTOMER;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO BANK_ACCOUNT;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO BANK_TRANSACTION;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO BANK_NOTIFICATION;
