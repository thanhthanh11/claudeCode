-- =============================================================
-- 17_transaction_interbank.sql — transaction-service (schema BANK_TRANSACTION)
-- Chuyển tiền liên ngân hàng qua Napas: loại giao dịch INTERBANK_OUT (chuyển đi) / INTERBANK_IN (tiền đến),
-- bước Saga INTERBANK_REQUESTED, thông tin đối tác ở ngân hàng khác, biểu phí và hạn mức chuyển đi.
-- Chạy bằng user bank_transaction hoặc bank_admin, đặt NLS_LANG=AMERICAN_AMERICA.AL32UTF8.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_TRANSACTION;

-- Đối tác ở ngân hàng khác: người nhận (INTERBANK_OUT) hoặc người gửi (INTERBANK_IN).
-- COUNTERPARTY_NAME lưu dạng mã hóa AES-GCM (enc:v1:...) nên cột rộng hơn tên gốc.
ALTER TABLE TRANSACTIONS ADD (
    COUNTERPARTY_BANK_CODE  VARCHAR2(20 CHAR),
    COUNTERPARTY_ACCOUNT    VARCHAR2(34 CHAR),
    COUNTERPARTY_NAME       VARCHAR2(400 CHAR),
    EXTERNAL_REF            VARCHAR2(64 CHAR)
);
CREATE UNIQUE INDEX UK_TRANSACTIONS_EXTERNAL_REF ON TRANSACTIONS (
    CASE WHEN EXTERNAL_REF IS NOT NULL THEN TRANSACTION_TYPE END,
    EXTERNAL_REF);
COMMENT ON COLUMN TRANSACTIONS.COUNTERPARTY_BANK_CODE IS 'Mã ngân hàng đối tác (BIN Napas) của giao dịch liên ngân hàng';
COMMENT ON COLUMN TRANSACTIONS.COUNTERPARTY_ACCOUNT IS 'Số tài khoản ở ngân hàng đối tác';
COMMENT ON COLUMN TRANSACTIONS.COUNTERPARTY_NAME IS 'Tên chủ tài khoản đối tác, mã hóa AES-GCM (enc:v1:...)';
COMMENT ON COLUMN TRANSACTIONS.EXTERNAL_REF IS 'Mã tham chiếu Napas';

ALTER TABLE TRANSACTIONS DROP CONSTRAINT CK_TRANSACTIONS_TYPE;
ALTER TABLE TRANSACTIONS ADD CONSTRAINT CK_TRANSACTIONS_TYPE
    CHECK (TRANSACTION_TYPE IN ('TRANSFER', 'DEPOSIT', 'WITHDRAWAL', 'INTERBANK_OUT', 'INTERBANK_IN'));

ALTER TABLE TRANSACTIONS DROP CONSTRAINT CK_TRANSACTIONS_SAGA_STEP;
ALTER TABLE TRANSACTIONS ADD CONSTRAINT CK_TRANSACTIONS_SAGA_STEP
    CHECK (SAGA_STEP IN ('DEBIT_REQUESTED', 'DEBITED', 'CREDIT_REQUESTED', 'CREDITED', 'INTERBANK_REQUESTED',
                         'COMPENSATION_REQUESTED', 'COMPENSATED'));

ALTER TABLE TRANSACTIONS DROP CONSTRAINT CK_TRANSACTIONS_ACCOUNTS;
ALTER TABLE TRANSACTIONS ADD CONSTRAINT CK_TRANSACTIONS_ACCOUNTS CHECK (
    (TRANSACTION_TYPE = 'TRANSFER'      AND FROM_ACCOUNT_NUMBER IS NOT NULL AND TO_ACCOUNT_NUMBER IS NOT NULL
                                        AND FROM_ACCOUNT_NUMBER <> TO_ACCOUNT_NUMBER) OR
    (TRANSACTION_TYPE = 'DEPOSIT'       AND TO_ACCOUNT_NUMBER IS NOT NULL) OR
    (TRANSACTION_TYPE = 'WITHDRAWAL'    AND FROM_ACCOUNT_NUMBER IS NOT NULL) OR
    (TRANSACTION_TYPE = 'INTERBANK_OUT' AND FROM_ACCOUNT_NUMBER IS NOT NULL AND TO_ACCOUNT_NUMBER IS NULL
                                        AND COUNTERPARTY_BANK_CODE IS NOT NULL AND COUNTERPARTY_ACCOUNT IS NOT NULL) OR
    (TRANSACTION_TYPE = 'INTERBANK_IN'  AND TO_ACCOUNT_NUMBER IS NOT NULL AND FROM_ACCOUNT_NUMBER IS NULL
                                        AND COUNTERPARTY_BANK_CODE IS NOT NULL AND EXTERNAL_REF IS NOT NULL)
);

ALTER TABLE TRANSACTION_LIMITS DROP CONSTRAINT CK_LIMITS_TYPE;
ALTER TABLE TRANSACTION_LIMITS ADD CONSTRAINT CK_LIMITS_TYPE
    CHECK (TRANSACTION_TYPE IN ('TRANSFER', 'DEPOSIT', 'WITHDRAWAL', 'INTERBANK_OUT'));

ALTER TABLE FEE_SCHEDULES DROP CONSTRAINT CK_FEE_TYPE;
ALTER TABLE FEE_SCHEDULES ADD CONSTRAINT CK_FEE_TYPE
    CHECK (TRANSACTION_TYPE IN ('TRANSFER', 'WITHDRAWAL', 'INTERBANK_OUT'));

-- Hạn mức chuyển đi liên ngân hàng: tối đa 499.999.999 VND/lần theo chuẩn Napas 247
INSERT INTO TRANSACTION_LIMITS (TRANSACTION_TYPE, ACCOUNT_TYPE, CURRENCY, PER_TXN_MAX, DAILY_MAX, DAILY_COUNT_MAX)
VALUES ('INTERBANK_OUT', NULL, 'VND', 499999999, 1000000000, 50);
INSERT INTO TRANSACTION_LIMITS (TRANSACTION_TYPE, ACCOUNT_TYPE, CURRENCY, PER_TXN_MAX, DAILY_MAX, DAILY_COUNT_MAX)
VALUES ('INTERBANK_OUT', 'SAVINGS', 'VND', 100000000, 300000000, 10);

-- Biểu phí chuyển đi liên ngân hàng VND: 0,03%, tối thiểu 3.000, tối đa 30.000
INSERT INTO FEE_SCHEDULES (TRANSACTION_TYPE, CURRENCY, FIXED_FEE, PERCENT_RATE, MIN_FEE, MAX_FEE)
VALUES ('INTERBANK_OUT', 'VND', 0, 0.0003, 3000, 30000);

COMMIT;
