-- =============================================================
-- 04_transaction_schema.sql — transaction-service (schema BANK_TRANSACTION)
-- Giao dịch chuyển tiền (Saga) và outbox để publish sự kiện Kafka.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_TRANSACTION;

CREATE TABLE TRANSACTIONS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    TRANSACTION_REF      VARCHAR2(40 CHAR)   NOT NULL,
    IDEMPOTENCY_KEY      VARCHAR2(64 CHAR)   NOT NULL,
    FROM_ACCOUNT_NUMBER  VARCHAR2(20 CHAR),
    TO_ACCOUNT_NUMBER    VARCHAR2(20 CHAR),
    AMOUNT               NUMBER(19,4)        NOT NULL,
    FEE                  NUMBER(19,4)        DEFAULT 0 NOT NULL,
    CURRENCY             CHAR(3 CHAR)        DEFAULT 'VND' NOT NULL,
    TRANSACTION_TYPE     VARCHAR2(20 CHAR)   NOT NULL,
    STATUS               VARCHAR2(20 CHAR)   DEFAULT 'PENDING' NOT NULL,
    SAGA_STEP            VARCHAR2(30 CHAR),
    DESCRIPTION          VARCHAR2(255 CHAR),
    FAILURE_REASON       VARCHAR2(500 CHAR),
    INITIATED_BY         NUMBER(19),                     -- BANK_AUTH.USERS.ID
    COMPLETED_AT         TIMESTAMP,
    CREATED_AT           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (ID),
    CONSTRAINT UK_TRANSACTIONS_REF UNIQUE (TRANSACTION_REF),
    CONSTRAINT UK_TRANSACTIONS_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT CK_TRANSACTIONS_AMOUNT CHECK (AMOUNT > 0 AND FEE >= 0),
    CONSTRAINT CK_TRANSACTIONS_TYPE CHECK (TRANSACTION_TYPE IN ('TRANSFER', 'DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT CK_TRANSACTIONS_STATUS CHECK (STATUS IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'COMPENSATED')),
    CONSTRAINT CK_TRANSACTIONS_SAGA_STEP CHECK (SAGA_STEP IN ('DEBIT_REQUESTED', 'DEBITED', 'CREDIT_REQUESTED', 'CREDITED',
                                                             'COMPENSATION_REQUESTED', 'COMPENSATED')),
    CONSTRAINT CK_TRANSACTIONS_ACCOUNTS CHECK (
        (TRANSACTION_TYPE = 'TRANSFER'   AND FROM_ACCOUNT_NUMBER IS NOT NULL AND TO_ACCOUNT_NUMBER IS NOT NULL
                                         AND FROM_ACCOUNT_NUMBER <> TO_ACCOUNT_NUMBER) OR
        (TRANSACTION_TYPE = 'DEPOSIT'    AND TO_ACCOUNT_NUMBER IS NOT NULL) OR
        (TRANSACTION_TYPE = 'WITHDRAWAL' AND FROM_ACCOUNT_NUMBER IS NOT NULL)
    )
);
CREATE INDEX IX_TRANSACTIONS_FROM ON TRANSACTIONS (FROM_ACCOUNT_NUMBER, CREATED_AT);
CREATE INDEX IX_TRANSACTIONS_TO ON TRANSACTIONS (TO_ACCOUNT_NUMBER, CREATED_AT);
CREATE INDEX IX_TRANSACTIONS_STATUS ON TRANSACTIONS (STATUS);
COMMENT ON TABLE TRANSACTIONS IS 'Giao dịch tài chính, điều phối theo Saga';

CREATE TABLE OUTBOX_EVENTS (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    AGGREGATE_TYPE  VARCHAR2(50 CHAR)   NOT NULL,
    AGGREGATE_ID    VARCHAR2(40 CHAR)   NOT NULL,
    EVENT_TYPE      VARCHAR2(100 CHAR)  NOT NULL,
    TOPIC           VARCHAR2(150 CHAR)  NOT NULL,
    PAYLOAD         CLOB                NOT NULL,
    STATUS          VARCHAR2(20 CHAR)   DEFAULT 'NEW' NOT NULL,
    RETRY_COUNT     NUMBER(5)           DEFAULT 0 NOT NULL,
    PUBLISHED_AT    TIMESTAMP,
    CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OUTBOX_EVENTS PRIMARY KEY (ID),
    CONSTRAINT CK_OUTBOX_STATUS CHECK (STATUS IN ('NEW', 'PUBLISHED', 'FAILED')),
    CONSTRAINT CK_OUTBOX_PAYLOAD_JSON CHECK (PAYLOAD IS JSON)
);
CREATE INDEX IX_OUTBOX_STATUS_CREATED ON OUTBOX_EVENTS (STATUS, CREATED_AT);
COMMENT ON TABLE OUTBOX_EVENTS IS 'Transactional outbox: ghi sự kiện cùng transaction DB rồi publish lên Kafka';
