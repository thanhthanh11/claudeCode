-- Dead letter, hạn mức, biểu phí, đối soát, danh bạ người nhận, chuyển tiền định kỳ.
-- Chạy bằng user bank_transaction, đặt NLS_LANG=AMERICAN_AMERICA.AL32UTF8.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_TRANSACTION;

-- Message Kafka lỗi sau khi retry (topic <topic>.DLT) để tra cứu và replay
CREATE TABLE DEAD_LETTER_EVENTS (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    DLT_TOPIC       VARCHAR2(150 CHAR)   NOT NULL,
    ORIGINAL_TOPIC  VARCHAR2(150 CHAR)   NOT NULL,
    PARTITION_NO    NUMBER(10)           NOT NULL,
    OFFSET_NO       NUMBER(19)           NOT NULL,
    MESSAGE_KEY     VARCHAR2(200 CHAR),
    EVENT_TYPE      VARCHAR2(100 CHAR),
    PAYLOAD         CLOB,
    ERROR_MESSAGE   VARCHAR2(2000 CHAR),
    STATUS          VARCHAR2(20 CHAR)    DEFAULT 'NEW' NOT NULL,
    HANDLED_BY      VARCHAR2(100 CHAR),
    HANDLED_AT      TIMESTAMP,
    CREATED_AT      TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DEAD_LETTER_EVENTS PRIMARY KEY (ID),
    CONSTRAINT UK_DLT_POSITION UNIQUE (DLT_TOPIC, PARTITION_NO, OFFSET_NO),
    CONSTRAINT CK_DLT_STATUS CHECK (STATUS IN ('NEW', 'REPLAYED', 'IGNORED'))
);
CREATE INDEX IX_DLT_STATUS ON DEAD_LETTER_EVENTS (STATUS, CREATED_AT);
COMMENT ON TABLE DEAD_LETTER_EVENTS IS 'Message Kafka bị đẩy vào DLT, chờ nhân viên replay/bỏ qua';

-- Hạn mức giao dịch. ACCOUNT_TYPE null = áp dụng mọi loại tài khoản; giới hạn null = không giới hạn
CREATE TABLE TRANSACTION_LIMITS (
    ID                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    TRANSACTION_TYPE  VARCHAR2(20 CHAR)   NOT NULL,
    ACCOUNT_TYPE      VARCHAR2(20 CHAR),
    CURRENCY          CHAR(3 CHAR)        NOT NULL,
    PER_TXN_MAX       NUMBER(19,4),
    DAILY_MAX         NUMBER(19,4),
    DAILY_COUNT_MAX   NUMBER(5),
    CREATED_AT        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSACTION_LIMITS PRIMARY KEY (ID),
    CONSTRAINT UK_TRANSACTION_LIMITS UNIQUE (TRANSACTION_TYPE, ACCOUNT_TYPE, CURRENCY),
    CONSTRAINT CK_LIMITS_TYPE CHECK (TRANSACTION_TYPE IN ('TRANSFER', 'DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT CK_LIMITS_VALUES CHECK ((PER_TXN_MAX IS NULL OR PER_TXN_MAX > 0) AND (DAILY_MAX IS NULL OR DAILY_MAX > 0)
                                       AND (DAILY_COUNT_MAX IS NULL OR DAILY_COUNT_MAX > 0))
);
COMMENT ON TABLE TRANSACTION_LIMITS IS 'Hạn mức giao dịch theo lần / theo ngày';

-- Một dòng mỗi tài khoản, khóa FOR UPDATE để tuần tự hóa việc kiểm tra hạn mức của cùng tài khoản
CREATE TABLE ACCOUNT_LIMIT_LOCKS (
    ACCOUNT_NUMBER  VARCHAR2(20 CHAR)  NOT NULL,
    CREATED_AT      TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ACCOUNT_LIMIT_LOCKS PRIMARY KEY (ACCOUNT_NUMBER)
);

-- Biểu phí: phí = FIXED_FEE + AMOUNT * PERCENT_RATE, chặn trong [MIN_FEE, MAX_FEE]
CREATE TABLE FEE_SCHEDULES (
    ID                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    TRANSACTION_TYPE  VARCHAR2(20 CHAR)   NOT NULL,
    CURRENCY          CHAR(3 CHAR)        NOT NULL,
    FIXED_FEE         NUMBER(19,4)        DEFAULT 0 NOT NULL,
    PERCENT_RATE      NUMBER(9,6)         DEFAULT 0 NOT NULL,   -- 0.0002 = 0,02%
    MIN_FEE           NUMBER(19,4)        DEFAULT 0 NOT NULL,
    MAX_FEE           NUMBER(19,4),
    ACTIVE            NUMBER(1)           DEFAULT 1 NOT NULL,
    CREATED_AT        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FEE_SCHEDULES PRIMARY KEY (ID),
    CONSTRAINT UK_FEE_SCHEDULES UNIQUE (TRANSACTION_TYPE, CURRENCY),
    CONSTRAINT CK_FEE_TYPE CHECK (TRANSACTION_TYPE IN ('TRANSFER', 'WITHDRAWAL')),
    CONSTRAINT CK_FEE_VALUES CHECK (FIXED_FEE >= 0 AND PERCENT_RATE >= 0 AND PERCENT_RATE < 1 AND MIN_FEE >= 0
                                    AND (MAX_FEE IS NULL OR MAX_FEE >= MIN_FEE)),
    CONSTRAINT CK_FEE_ACTIVE CHECK (ACTIVE IN (0, 1))
);
COMMENT ON TABLE FEE_SCHEDULES IS 'Biểu phí giao dịch (thu trên tài khoản nguồn)';

-- Sai lệch giữa giao dịch và bút toán sổ cái
CREATE TABLE RECONCILIATION_ISSUES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    TRANSACTION_REF  VARCHAR2(40 CHAR)    NOT NULL,
    ISSUE_TYPE       VARCHAR2(30 CHAR)    NOT NULL,
    DETAIL           VARCHAR2(1000 CHAR),
    DETECTED_AT      TIMESTAMP            NOT NULL,
    RESOLVED         NUMBER(1)            DEFAULT 0 NOT NULL,
    RESOLVED_AT      TIMESTAMP,
    NOTE             VARCHAR2(500 CHAR),
    CREATED_AT       TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TXN_RECON_ISSUES PRIMARY KEY (ID),
    CONSTRAINT CK_TXN_RECON_TYPE CHECK (ISSUE_TYPE IN ('LEDGER_MISMATCH', 'LOOKUP_FAILED')),
    CONSTRAINT CK_TXN_RECON_RESOLVED CHECK (RESOLVED IN (0, 1))
);
CREATE INDEX IX_TXN_RECON_REF ON RECONCILIATION_ISSUES (TRANSACTION_REF, RESOLVED);
COMMENT ON TABLE RECONCILIATION_ISSUES IS 'Giao dịch có bút toán sổ cái không khớp kết quả';

-- Danh bạ người nhận của khách hàng
CREATE TABLE BENEFICIARIES (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID     NUMBER(19)          NOT NULL,        -- BANK_CUSTOMER.CUSTOMERS.ID
    ACCOUNT_NUMBER  VARCHAR2(20 CHAR)   NOT NULL,
    NICKNAME        VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_BENEFICIARIES PRIMARY KEY (ID),
    CONSTRAINT UK_BENEFICIARIES UNIQUE (CUSTOMER_ID, ACCOUNT_NUMBER)
);
COMMENT ON TABLE BENEFICIARIES IS 'Danh bạ tài khoản người nhận của khách hàng';

-- Lệnh chuyển tiền định kỳ
CREATE TABLE SCHEDULED_TRANSFERS (
    ID                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID           NUMBER(19)          NOT NULL,
    CREATED_BY            NUMBER(19)          NOT NULL,   -- BANK_AUTH.USERS.ID
    FROM_ACCOUNT_NUMBER   VARCHAR2(20 CHAR)   NOT NULL,
    TO_ACCOUNT_NUMBER     VARCHAR2(20 CHAR)   NOT NULL,
    AMOUNT                NUMBER(19,4)        NOT NULL,
    DESCRIPTION           VARCHAR2(255 CHAR),
    FREQUENCY             VARCHAR2(20 CHAR)   NOT NULL,
    START_DATE            DATE                NOT NULL,
    END_DATE              DATE,
    NEXT_RUN_DATE         DATE                NOT NULL,
    STATUS                VARCHAR2(20 CHAR)   DEFAULT 'ACTIVE' NOT NULL,
    RUN_COUNT             NUMBER(10)          DEFAULT 0 NOT NULL,
    LAST_RUN_DATE         DATE,
    LAST_TRANSACTION_REF  VARCHAR2(40 CHAR),
    LAST_ERROR            VARCHAR2(500 CHAR),
    CREATED_AT            TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SCHEDULED_TRANSFERS PRIMARY KEY (ID),
    CONSTRAINT CK_SCHED_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_SCHED_FREQUENCY CHECK (FREQUENCY IN ('DAILY', 'WEEKLY', 'MONTHLY')),
    CONSTRAINT CK_SCHED_STATUS CHECK (STATUS IN ('ACTIVE', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT CK_SCHED_ACCOUNTS CHECK (FROM_ACCOUNT_NUMBER <> TO_ACCOUNT_NUMBER),
    CONSTRAINT CK_SCHED_DATES CHECK (END_DATE IS NULL OR END_DATE >= START_DATE)
);
CREATE INDEX IX_SCHED_DUE ON SCHEDULED_TRANSFERS (STATUS, NEXT_RUN_DATE);
CREATE INDEX IX_SCHED_CUSTOMER ON SCHEDULED_TRANSFERS (CUSTOMER_ID);
COMMENT ON TABLE SCHEDULED_TRANSFERS IS 'Lệnh chuyển tiền định kỳ của khách hàng';

