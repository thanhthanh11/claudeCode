-- =============================================================
-- 02_customer_schema.sql — customer-service (schema BANK_CUSTOMER)
-- Hồ sơ khách hàng và KYC.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_CUSTOMER;

CREATE TABLE CUSTOMERS (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USER_ID        NUMBER(19),                          -- tham chiếu BANK_AUTH.USERS.ID (không FK liên schema)
    CUSTOMER_CODE  VARCHAR2(20 CHAR)   NOT NULL,
    FULL_NAME      VARCHAR2(150 CHAR)  NOT NULL,
    DATE_OF_BIRTH  DATE                NOT NULL,
    GENDER         VARCHAR2(10 CHAR),
    ID_TYPE        VARCHAR2(20 CHAR)   NOT NULL,
    ID_NUMBER      VARCHAR2(20 CHAR)   NOT NULL,
    PHONE          VARCHAR2(20 CHAR)   NOT NULL,
    EMAIL          VARCHAR2(150 CHAR),
    ADDRESS        VARCHAR2(500 CHAR),
    KYC_STATUS     VARCHAR2(20 CHAR)   DEFAULT 'PENDING' NOT NULL,
    STATUS         VARCHAR2(20 CHAR)   DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (ID),
    CONSTRAINT UK_CUSTOMERS_CODE UNIQUE (CUSTOMER_CODE),
    CONSTRAINT UK_CUSTOMERS_ID_NUMBER UNIQUE (ID_TYPE, ID_NUMBER),
    CONSTRAINT UK_CUSTOMERS_USER UNIQUE (USER_ID),
    CONSTRAINT CK_CUSTOMERS_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT CK_CUSTOMERS_ID_TYPE CHECK (ID_TYPE IN ('CCCD', 'CMND', 'PASSPORT')),
    CONSTRAINT CK_CUSTOMERS_KYC CHECK (KYC_STATUS IN ('PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT CK_CUSTOMERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'BLOCKED'))
);
CREATE INDEX IX_CUSTOMERS_PHONE ON CUSTOMERS (PHONE);
COMMENT ON TABLE CUSTOMERS IS 'Hồ sơ khách hàng';

CREATE TABLE KYC_DOCUMENTS (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID    NUMBER(19)          NOT NULL,
    DOCUMENT_TYPE  VARCHAR2(30 CHAR)   NOT NULL,
    FILE_URL       VARCHAR2(500 CHAR)  NOT NULL,
    STATUS         VARCHAR2(20 CHAR)   DEFAULT 'PENDING' NOT NULL,
    REVIEWED_BY    VARCHAR2(50 CHAR),
    REVIEWED_AT    TIMESTAMP,
    NOTE           VARCHAR2(500 CHAR),
    CREATED_AT     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_KYC_DOCUMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_KYC_DOCUMENTS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (ID),
    CONSTRAINT CK_KYC_DOCUMENTS_TYPE CHECK (DOCUMENT_TYPE IN ('ID_FRONT', 'ID_BACK', 'PORTRAIT', 'OTHER')),
    CONSTRAINT CK_KYC_DOCUMENTS_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED'))
);
CREATE INDEX IX_KYC_DOCUMENTS_CUSTOMER ON KYC_DOCUMENTS (CUSTOMER_ID);
COMMENT ON TABLE KYC_DOCUMENTS IS 'Giấy tờ định danh khách hàng (KYC)';
