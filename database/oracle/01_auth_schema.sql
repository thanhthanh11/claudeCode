-- =============================================================
-- 01_auth_schema.sql — auth-service (schema BANK_AUTH)
-- Người dùng, RBAC (role/permission), refresh token.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_AUTH;

CREATE TABLE USERS (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USERNAME            VARCHAR2(50 CHAR)   NOT NULL,
    PASSWORD_HASH       VARCHAR2(255 CHAR)  NOT NULL,
    EMAIL               VARCHAR2(150 CHAR)  NOT NULL,
    STATUS              VARCHAR2(20 CHAR)   DEFAULT 'ACTIVE' NOT NULL,
    FAILED_LOGIN_COUNT  NUMBER(3)           DEFAULT 0 NOT NULL,
    LOCKED_UNTIL        TIMESTAMP,
    LAST_LOGIN_AT       TIMESTAMP,
    CREATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED', 'DISABLED'))
);
COMMENT ON TABLE USERS IS 'Tài khoản đăng nhập hệ thống';

CREATE TABLE ROLES (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODE         VARCHAR2(50 CHAR)  NOT NULL,
    NAME         VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION  VARCHAR2(255 CHAR),
    CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UK_ROLES_CODE UNIQUE (CODE)
);
COMMENT ON TABLE ROLES IS 'Vai trò (RBAC)';

CREATE TABLE PERMISSIONS (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODE         VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION  VARCHAR2(255 CHAR),
    CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PERMISSIONS PRIMARY KEY (ID),
    CONSTRAINT UK_PERMISSIONS_CODE UNIQUE (CODE)
);
COMMENT ON TABLE PERMISSIONS IS 'Quyền chi tiết (RBAC)';

CREATE TABLE USER_ROLES (
    USER_ID  NUMBER(19) NOT NULL,
    ROLE_ID  NUMBER(19) NOT NULL,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_USER_ROLES_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID)
);
CREATE INDEX IX_USER_ROLES_ROLE ON USER_ROLES (ROLE_ID);

CREATE TABLE ROLE_PERMISSIONS (
    ROLE_ID        NUMBER(19) NOT NULL,
    PERMISSION_ID  NUMBER(19) NOT NULL,
    CONSTRAINT PK_ROLE_PERMISSIONS PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERM_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROLE_PERM_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS (ID)
);
CREATE INDEX IX_ROLE_PERM_PERM ON ROLE_PERMISSIONS (PERMISSION_ID);

CREATE TABLE REFRESH_TOKENS (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USER_ID     NUMBER(19)          NOT NULL,
    TOKEN_HASH  VARCHAR2(255 CHAR)  NOT NULL,
    EXPIRES_AT  TIMESTAMP           NOT NULL,
    REVOKED     NUMBER(1)           DEFAULT 0 NOT NULL,
    CREATED_AT  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REFRESH_TOKENS PRIMARY KEY (ID),
    CONSTRAINT UK_REFRESH_TOKENS_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_REFRESH_TOKENS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_REFRESH_TOKENS_REVOKED CHECK (REVOKED IN (0, 1))
);
CREATE INDEX IX_REFRESH_TOKENS_USER ON REFRESH_TOKENS (USER_ID);
COMMENT ON TABLE REFRESH_TOKENS IS 'Refresh token JWT (lưu hash, không lưu token gốc)';

