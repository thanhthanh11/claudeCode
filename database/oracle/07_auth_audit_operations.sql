-- 07_auth_audit_operations.sql — auth-service (schema BANK_AUTH)
-- Permission vận hành OPERATION_MANAGE (cấp cho ADMIN) và bảng audit log tập trung.
-- Chạy bằng user bank_auth, đặt NLS_LANG=AMERICAN_AMERICA.AL32UTF8.
-- =============================================================
ALTER SESSION SET CURRENT_SCHEMA = BANK_AUTH;

INSERT INTO PERMISSIONS (CODE, DESCRIPTION)
VALUES ('OPERATION_MANAGE', 'Vận hành: xử lý giao dịch lỗi, outbox, DLT, đối soát');

INSERT INTO ROLE_PERMISSIONS (ROLE_ID, PERMISSION_ID)
SELECT r.ID, p.ID FROM ROLES r, PERMISSIONS p
WHERE r.CODE = 'ADMIN' AND p.CODE = 'OPERATION_MANAGE';

CREATE TABLE AUDIT_LOGS (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    EVENT_ID        VARCHAR2(64 CHAR)    NOT NULL,      -- EventEnvelope.eventId, chống ghi trùng
    SERVICE_NAME    VARCHAR2(50 CHAR)    NOT NULL,
    ACTOR_USER_ID   NUMBER(19),                         -- null với hành động của hệ thống
    ACTOR_USERNAME  VARCHAR2(100 CHAR)   NOT NULL,
    ACTION          VARCHAR2(60 CHAR)    NOT NULL,
    TARGET_TYPE     VARCHAR2(50 CHAR),
    TARGET_ID       VARCHAR2(100 CHAR),
    DETAIL          VARCHAR2(1000 CHAR),
    OCCURRED_AT     TIMESTAMP            NOT NULL,
    CREATED_AT      TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDIT_LOGS PRIMARY KEY (ID),
    CONSTRAINT UK_AUDIT_LOGS_EVENT UNIQUE (EVENT_ID)
);
CREATE INDEX IX_AUDIT_LOGS_OCCURRED ON AUDIT_LOGS (OCCURRED_AT);
CREATE INDEX IX_AUDIT_LOGS_ACTOR ON AUDIT_LOGS (ACTOR_USER_ID, OCCURRED_AT);
CREATE INDEX IX_AUDIT_LOGS_TARGET ON AUDIT_LOGS (TARGET_TYPE, TARGET_ID);
COMMENT ON TABLE AUDIT_LOGS IS 'Audit hành động của người dùng/nhân viên trên mọi service (chỉ thêm mới)';

COMMIT;
